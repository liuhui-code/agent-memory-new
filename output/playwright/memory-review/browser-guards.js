async (page) => {
  const checks=[];
  const check=(name,ok)=>{if(!ok) throw new Error(name);checks.push(name);};
  const ready=async(p)=>{await p.waitForFunction(()=>document.getElementById('record-list').getAttribute('aria-busy')==='false');};
  await page.reload(); await ready(page);
  await page.getByRole('searchbox',{name:'搜索记忆'}).fill('WORKBENCH_XSS');
  await page.waitForFunction(()=>document.getElementById('result-count').textContent==='1 条匹配');
  check('untrusted HTML is visible as literal text', (await page.locator('.record-title').innerText()).includes('<img src=x'));
  check('untrusted HTML does not create DOM or execute', await page.locator('#record-list img, #record-list script').count()===0 && await page.evaluate(()=>window.reviewXss===undefined));
  await page.locator('.record-open').click();
  await page.getByRole('button',{name:'归档',exact:true}).click();
  const other=await page.context().newPage();
  await other.goto(page.url()); await ready(other);
  await other.getByRole('searchbox',{name:'搜索记忆'}).fill('WORKBENCH_XSS');
  await other.waitForFunction(()=>document.getElementById('result-count').textContent==='1 条匹配');
  await other.locator('.record-open').click();
  await other.getByRole('button',{name:'标记已审查',exact:true}).click();
  await other.waitForFunction(()=>document.getElementById('toast').textContent.includes('已标记已审查'));
  await page.locator('#dialog-submit').click();
  await page.locator('#dialog-error').waitFor();
  check('stale browser selection fails visibly without archival', (await page.locator('#dialog-error').innerText()).includes('已被其他操作更新'));
  await page.getByRole('button',{name:'取消',exact:true}).click();
  await page.getByRole('button',{name:'刷新记忆库',exact:true}).click(); await ready(page);
  check('conflicting record remains active', (await page.locator('.record-meta .status').first().innerText())==='有效');
  await other.close();
  await page.getByRole('searchbox',{name:'搜索记忆'}).fill('');
  await page.waitForFunction(()=>document.querySelectorAll('.record-row').length===30);
  await page.getByRole('combobox',{name:'记忆类型筛选'}).selectOption('reflection'); await ready(page);
  await page.locator('.record-open').first().click();
  await page.getByRole('button',{name:'标记已审查',exact:true}).waitFor();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'output/playwright/memory-review/desktop-final.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'output/playwright/memory-review/mobile-detail-final.png'});
  check('mobile toast cannot intercept clicks', await page.locator('#toast').evaluate(el=>getComputedStyle(el).pointerEvents==='none'));
  await page.getByRole('button',{name:'关闭详情',exact:true}).click();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'output/playwright/memory-review/mobile-final.png',fullPage:true});
  check('final mobile layout has no horizontal overflow', await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  return {passed:checks.length,checks,fixture_origin:'generated development records'};
}
